test("routing helpers", () => {
  assert.deepEqual(splitModel("a/b#high"), { model: "a/b", variant: "high" })
  assert.deepEqual(splitModel("a/b"), { model: "a/b" })
  assert.deepEqual(modelRef("a/b/c", "x"), { providerID: "a", id: "b/c", variant: "x" })
  assert.deepEqual(routesFrom(undefined), {})
  assert.deepEqual(routesFrom({ profiles: { p: { model: "nope" } }, agents: { x: "p", y: "missing" } }), {})
  assert.deepEqual(unsupportedVariants({ a: { model: "p/m", variant: "v" } }, [{ providerID: "p", id: "m", variants: [{ id: "v" }] }]), [])
  assert.deepEqual(guardVerdict({ stdout: '{"decision":"maybe"}' }), undefined)
})

test("generated agent files parse; a malformed one fails loudly", () => {
  const agents = loadAgents(PACKAGE_ROOT)
  assert.deepEqual(agents.map((a) => a.name), ROSTER)
  assert.equal(agents.find((a) => a.name === "aid-explorer").readOnly, true)
  assert.throws(() => parseAgentFile("no frontmatter"), /missing frontmatter/)
  assert.throws(() => parseAgentFile("---\nmode: subagent\n---\nbody"), /description and mode/)
})
