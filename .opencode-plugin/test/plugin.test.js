import assert from "node:assert/strict"
import test from "node:test"

import plugin from "../../index.js"
import { ORCHESTRATOR, READ_ONLY_RULE, loadAgents, parseAgentFile } from "../src/agents.js"
import { modelRef, routesFrom, splitModel, unsupportedVariants } from "../src/routing.js"
import { PACKAGE_ROOT, createSetup, guardVerdict } from "../src/setup.js"
import { fakeAid, fakeContext, ok } from "./fake-opencode.js"

const ROSTER = ["aid-craftsman", "aid-creator", "aid-designer", "aid-explorer", "aid-mechanic", "aid-oracle", "aid-orchestrator"]

const CONFIG = {
  source: ".opencode/aid.json",
  profiles: {
    fast: { model: "acme/fast-1" },
    deep: { model: "acme/deep-2#high", reasoning_effort: "high" },
  },
  agents: { "aid-explorer": "fast", "aid-oracle": "deep", "aid-orchestrator": "deep" },
  hide_free_models: false,
}

const CATALOG = [
  { providerID: "acme", id: "fast-1", variants: [] },
  { providerID: "acme", id: "deep-2", variants: ["high"] },
]

const standardAid = (overrides = {}) =>
  fakeAid({
    "config --harness opencode --json": ok(JSON.stringify(CONFIG)),
    "guard policy --harness opencode": ok("Route work to the aid-* roster."),
    "guard opencode-tool": ok(JSON.stringify({ decision: "allow" })),
    ...overrides,
  })

async function boot({ aid = standardAid().aid, catalog = CATALOG, existingAgents, logs = [] } = {}) {
  const fake = fakeContext({ catalog, existingAgents })
  const dispose = await createSetup({ aid, log: (line) => logs.push(line) })(fake.ctx)
  return { ...fake, dispose, logs }
}

test("the entry exports only a default {id, setup}", async () => {
  const module = await import("../../index.js")
  assert.deepEqual(Object.keys(module), ["default"])
  assert.equal(plugin.id, "ai-development")
  assert.equal(typeof plugin.setup, "function")
})

test("a context without agent.transform (not OpenCode 2) is left alone", async () => {
  assert.equal(await createSetup({ aid: standardAid().aid })({}), undefined)
})

test("all seven aid-* agents register with their modes, prompts and the orchestrator as default", async () => {
  const { agents, state, dispose } = await boot()
  for (const name of ROSTER) assert.ok(agents.has(name), `${name} registered`)
  assert.equal(agents.get(ORCHESTRATOR).mode, "primary")
  for (const name of ROSTER.filter((n) => n !== ORCHESTRATOR)) assert.equal(agents.get(name).mode, "subagent", name)
  assert.equal(state.defaultAgent, ORCHESTRATOR)
  assert.match(agents.get("aid-explorer").system, /^You are the explorer\./)
  assert.doesNotMatch(agents.get("aid-explorer").system, /Generated by/)
  assert.ok(agents.get("aid-mechanic").description.length > 20)
  await dispose()
})

test("read-only agents get the edit-deny rule, others don't, and it isn't duplicated on reload", async () => {
  const { agents, ctx, dispose } = await boot()
  const denies = (name) => agents.get(name).permissions.filter((r) => r.action === "edit" && r.resource === "*" && r.effect === "deny").length
  assert.equal(denies("aid-explorer"), 1)
  assert.equal(denies("aid-mechanic"), 0)
  await ctx.agent.reload()
  assert.equal(denies("aid-explorer"), 1)
  assert.deepEqual(READ_ONLY_RULE, { action: "edit", resource: "*", effect: "deny" })
  await dispose()
})

test("all 21 skills register in place, without frontmatter, replacing older copies", async () => {
  const fake = fakeContext({ catalog: CATALOG })
  await fake.ctx.skill.transform((editor) => editor.add({ id: "aid-prd", name: "aid-prd", content: "stale" }))
  const dispose = await createSetup({ aid: standardAid().aid, log: () => {} })(fake.ctx)
  assert.equal(fake.skills.size, 21)
  const prd = fake.skills.get("aid-prd")
  assert.notEqual(prd.content, "stale")
  assert.doesNotMatch(prd.content, /^---/)
  assert.ok(prd.path.startsWith(PACKAGE_ROOT))
  await dispose()
})

