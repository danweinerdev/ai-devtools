test("reasoning effort from the profile is applied in session hooks, never overriding one already set", async () => {
  const { hooks, dispose } = await boot()
  const event = { agent: "aid-oracle", options: {}, system: [] }
  await hooks.session.generate(event)
  assert.equal(event.options.reasoningEffort, "high")
  const preset = { agent: "aid-oracle", options: { reasoningEffort: "low" } }
  await hooks.session.generate(preset)
  assert.equal(preset.options.reasoningEffort, "low")
  const unmapped = { agent: "aid-mechanic", options: {} }
  await hooks.session.generate(unmapped)
  assert.equal(unmapped.options.reasoningEffort, undefined)
  await dispose()
})

test("an invalid config is surfaced loudly and agents register without routing", async () => {
  const logs = []
  const { aid } = standardAid({
    "config --harness opencode --json": { ok: false, code: 1, stdout: "", stderr: ".opencode/aid.json is invalid: unknown key `modles`", missing: false },
  })
  const { agents, hooks, dispose } = await boot({ aid, logs })
  assert.ok(logs.some((line) => line.includes("model routing is off") && line.includes("modles")))
  assert.equal(agents.get("aid-explorer").model, undefined)
  assert.equal(agents.size, 7)
  const event = { agent: ORCHESTRATOR, options: {}, system: [] }
  await hooks.session.context(event)
  assert.ok(event.system.some((part) => part.text.includes("modles")), "the orchestrator is told too")
  await dispose()
})

